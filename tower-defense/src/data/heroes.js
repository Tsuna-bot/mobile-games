export const HERO_ORDER = ['knight', 'archer', 'frost', 'engineer', 'priestess'];

export function heroDef(id) {
  return HEROES[id] ?? HEROES.knight;
}

/** Stats of hero `def` at `level` (1-based); `threat` scales with the current wave. */
export function heroStats(level, threat = 1, def = HEROES.knight) {
  const scale = 0.65 + 0.35 * threat;
  return {
    damage: def.damage * (1 + 0.28 * (level - 1)) * scale,
    maxHp: Math.round(def.hp * (1 + 0.2 * (level - 1)) * Math.sqrt(scale)),
    range: def.range + 0.05 * (level - 1),
    rate: def.rate * (1 - 0.03 * (level - 1)),
  };
}
